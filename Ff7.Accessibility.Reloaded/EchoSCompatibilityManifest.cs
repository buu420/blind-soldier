    private static IReadOnlyDictionary<int, HashSet<string>> CreateAlternateEchoS124Fingerprints()
    {
        var result = new Dictionary<int, HashSet<string>>();
        foreach (var line in RawAlternateEchoS124Fingerprints.Split(
                     '\n',
                     StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var values = line.Split(',');
            if (values.Length < 2 || !int.TryParse(values[0], out var fieldId))
            {
                throw new InvalidOperationException($"Invalid Echo-S UI fingerprint row: {line}");
            }

            var hashes = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            for (var index = 1; index < values.Length; index++)
            {
                if (values[index].Length != 64 || !hashes.Add(values[index]))
                {
                    throw new InvalidOperationException($"Invalid Echo-S UI fingerprint row: {line}");
                }
            }

            result.Add(fieldId, hashes);
        }

        return result;
    }

    private static IReadOnlyList<FieldCutsceneDescriptionCue> CreateEchoCues()
    {
        var canonical = FieldCutsceneDescriptionCatalog.CreateEarlyGameDescriptions()
            .ToDictionary(cue => cue.Key);
        var result = new List<FieldCutsceneDescriptionCue>();
        foreach (var line in RawCueMappings.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var values = line.Split(',').Select(int.Parse).ToArray();
            if (values.Length != 8)
            {
                throw new InvalidOperationException($"Invalid Echo-S compatibility row: {line}");
            }

            var vanillaKey = new FieldCutsceneDescriptionKey(values[0], values[1], values[2], values[3]);
            if (!canonical.TryGetValue(vanillaKey, out var cue))
            {
                throw new InvalidOperationException($"Echo-S compatibility row has no canonical cue: {line}");
            }

            result.Add(new FieldCutsceneDescriptionCue(
                values[0],
                values[4],
                values[5],
                values[6],
                cue.Text,
                values[7]));
        }

        return result;
    }

