    public static SupportedFieldScriptVariant ResolveVariant(LoadedFieldScriptIdentity identity)
    {
        if (!Fingerprints.TryGetValue(identity.FieldId, out var supported))
        {
            return SupportedFieldScriptVariant.Unknown;
        }

        if ((!string.IsNullOrWhiteSpace(supported.EchoS124) &&
             string.Equals(identity.ScriptPrefixSha256, supported.EchoS124, StringComparison.OrdinalIgnoreCase)) ||
            (AlternateEchoS124Fingerprints.TryGetValue(identity.FieldId, out var alternateFingerprints) &&
             alternateFingerprints.Contains(identity.ScriptPrefixSha256)))
        {
            return SupportedFieldScriptVariant.EchoS124;
        }

        return string.Equals(identity.ScriptPrefixSha256, supported.Vanilla, StringComparison.OrdinalIgnoreCase)
            ? SupportedFieldScriptVariant.Vanilla
            : SupportedFieldScriptVariant.Unknown;
    }

    public static bool IsSupportedDisclaimer(LoadedFieldScriptIdentity identity) =>
        identity.FieldId == 109 &&
        EchoS124DisclaimerFingerprints.Contains(identity.ScriptPrefixSha256);

    public static string? ResolveDisclaimerText(LoadedFieldScriptIdentity identity, int messageId) =>
        IsSupportedDisclaimer(identity) && DisclaimerText.TryGetValue(messageId, out var text)
            ? text
            : null;

    public static string? ResolveDisclaimerSpeechText(LoadedFieldScriptIdentity identity, int messageId)
    {
        var text = ResolveDisclaimerText(identity, messageId);
        return text is null ? null : $"{text} Press confirm to continue.";
    }

    public static byte ResolveObjectCollectedMask(
        LoadedFieldScriptIdentity identity,
        FieldNavigationObjectDefinition definition)
    {
        if (ResolveVariant(identity) == SupportedFieldScriptVariant.EchoS124 &&
            definition.FieldId == 116 &&
            definition.Kind == FieldNavigationObjectKind.Item &&
            definition.NativeId == 0 &&
            definition.CollectedBank == 15 &&
            definition.CollectedAddress == 32 &&
            definition.CollectedMask == 3)
        {
            return definition.EntityId switch
            {
                9 => 1,
                10 => 2,
                _ => definition.CollectedMask
            };
        }

        return definition.CollectedMask;
    }

