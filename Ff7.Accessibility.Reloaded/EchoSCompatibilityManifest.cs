/// <summary>
/// Selects one exact cue catalog after validating the loaded field script.
/// Unknown script variants intentionally receive no guessed description cue.
/// </summary>
public sealed class EchoSFieldCutsceneDescriptionTracker
{
    private readonly FieldCutsceneDescriptionTracker vanilla =
        new(FieldCutsceneDescriptionCatalog.CreateEarlyGameDescriptions());
    private readonly FieldCutsceneDescriptionTracker echoS124 =
        new(EchoSCompatibilityManifest.CreateEchoS124Descriptions());

    public FieldCutsceneDescriptionCue? Observe(
        FieldScriptContext context,
        LoadedFieldScriptIdentity identity)
    {
        if (identity.FieldId != context.FieldId)
        {
            return null;
        }

        return EchoSCompatibilityManifest.ResolveVariant(identity) switch
        {
            SupportedFieldScriptVariant.Vanilla => vanilla.Observe(context),
            SupportedFieldScriptVariant.EchoS124 => echoS124.Observe(context),
            _ => null
        };
    }

    public void Reset()
    {
        vanilla.Reset();
        echoS124.Reset();
    }
}
