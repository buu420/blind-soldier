using System.Buffers.Binary;
using Ff7.Accessibility.LegacyLayout;

namespace Ff7.Accessibility.Reloaded.Tests;

internal static class NativeCreditsSnapshotReaderTests
{
    public static void Run()
    {
        ReadsOnlyNativeRendererRows();
        RequiresAnObservedRendererAndStaffCreditPhase();
        RejectsTornStateAndRows();
        RejectsUnterminatedOrUnsupportedText();
        DoesNotReadOffScreenNames();
        ReadsTheExactFinalNativeWindowWithoutPadding();
    }

    private static void ReadsOnlyNativeRendererRows()
    {
        var m = Create();
        m.Row(6, "EXECUTIVE PRODUCERS", 1);
        m.Row(7, "TETSUO MIZUNO", 0);
        // Independent installed cr_us.lgp PEOPLE.BIN records 6 and 7. These are
        // the actual font indices, not bytes generated by the reader's decoder.
        Convert.FromHexString("0417040214130815042F0F110E0314020411127F").CopyTo(m.Bytes[Memory.Pool + 6 * 64], 12);
        Convert.FromHexString("13041312140E2F0C0819140D0E7F").CopyTo(m.Bytes[Memory.Pool + 7 * 64], 12);
        Check(new NativeCreditsSnapshotReader().TryRead(m, true, out var s), "valid rendered staff credits must be readable");
        Check(s!.VisibleRows.Count == 2 && s.VisibleRows[0].Index == 6 && s.VisibleRows[1].Text == "TETSUO MIZUNO", "native rows and custom credits encoding");
    }

    private static void RequiresAnObservedRendererAndStaffCreditPhase()
    {
        var m = Create();
        var r = new NativeCreditsSnapshotReader();
        Check(!r.TryRead(m, false, out _), "loaded people.bin is not proof it is drawn");
        foreach (var (address, value) in new[] { (0x00CBF9DCu, 0x19), (0x00F4F408u, 0), (0x00F4F414u, 3), (0x00F4F44Cu, 0) })
        {
            m = Create(); m.Int(address, value);
            Check(!r.TryRead(m, true, out _), "wrong module, logos, end3, or stopped scrolling must reject staff names");
        }
    }

    private static void RejectsTornStateAndRows()
    {
        var r = new NativeCreditsSnapshotReader();
        foreach (var address in new[] { 0x00F4F328u, 0x00F4F340u, 0x00F4F42Cu, Memory.Pool + 6 * 64 })
        {
            var m = Create(); m.Row(6, "DIRECTOR", 1); m.MutateOnSecondRead = address;
            Check(!r.TryRead(m, true, out _), "changing index, offset, pool, or row must reject the whole snapshot");
        }
        var broken = Create(); broken.FailAddress = 0x00F4F340;
        Check(!r.TryRead(broken, true, out _), "an unreadable scroll position is not zero");
    }

    private static void RejectsUnterminatedOrUnsupportedText()
    {
        foreach (var value in new byte[] { 0, 0x50, 0x28 })
        {
            var m = Create(); var row = m.Bytes[Memory.Pool + 6 * 64];
            row.AsSpan(12, 48).Fill(value);
            if (value != 0) row[13] = 0x7F;
            Check(!new NativeCreditsSnapshotReader().TryRead(m, true, out _), "no guessed decoding for missing terminator or unknown glyph");
        }
    }

    private static void DoesNotReadOffScreenNames()
    {
        var m = Create(); m.Int(0x00F4F340, -40); m.Row(6, "OFF SCREEN", 0); m.Row(7, "DIRECTOR", 1);
        Check(new NativeCreditsSnapshotReader().TryRead(m, true, out var s), "visible row after clipped first row");
        Check(s!.VisibleRows.All(x => x.Index != 6), "do not expose a row whose baseline has left the viewport");
        Check(!m.TextReads.Contains(6) && !m.TextReads.Contains(17), "read text only for on-screen records in the native eleven-row draw window");
    }

    private static void ReadsTheExactFinalNativeWindowWithoutPadding()
    {
        var m = Create(); m.Int(0x00F4F328, 528); m.Int(0x00F4F424, 480);
        m.Row(528, "FIRST TAIL ROW", 0); m.Row(538, "LAST TAIL ROW", 0);
        Check(new NativeCreditsSnapshotReader().TryRead(m, true, out var last), "native final first-row528 remains readable");
        Check(last!.VisibleRows.Any(row => row.Index == 538 && row.Text == "LAST TAIL ROW"),
            "the final539th record is not lost");
        Check(m.TextReads.All(index => index <= 538), "final window never reads buffer padding");
        m = Create(); m.Int(0x00F4F328, 529);
        Check(!new NativeCreditsSnapshotReader().TryRead(m, true, out _),
            "first-row529 is not a native staff renderer state");
        Check(m.TextReads.Count == 0, "unsupported tail does not read nonexistent rows");
    }

    private static Memory Create()
    {
        var m = new Memory();
        m.Int(0x00CBF9DC, 0x1C); m.Int(0x00F4F408, 1); m.Int(0x00F4F414, 0);
        m.Int(0x00F4F44C, 1); m.Int(0x00F4F328, 6); m.Int(0x00F4F340, 0);
        m.Int(0x00F4F42C, (int)Memory.Pool); m.Int(0x00F4F424, 240);
        for (var i = 0; i < 539; i++) m.Row(i, " ", 0);
        return m;
    }

    private static void Check(bool condition, string reason)
    {
        if (!condition) throw new InvalidOperationException(reason);
    }

    private sealed class Memory : ILegacyAddressSpace
    {
        public const uint Pool = 0x02000000;
        public readonly Dictionary<uint, byte[]> Bytes = [];
        private readonly Dictionary<uint, int> reads = [];
        public readonly HashSet<int> TextReads = [];
        public uint MutateOnSecondRead;
        public uint FailAddress;
        public void Int(uint address, int value)
        {
            var b = new byte[4]; BinaryPrimitives.WriteInt32LittleEndian(b, value); Bytes[address] = b;
        }
        public void Row(int index, string text, int style)
        {
            var b = new byte[64]; BinaryPrimitives.WriteInt32LittleEndian(b, style);
            BinaryPrimitives.WriteInt32LittleEndian(b.AsSpan(4), 1);
            BinaryPrimitives.WriteInt32LittleEndian(b.AsSpan(60), 40);
            for (var j = 0; j < text.Length; j++) b[12 + j] = text[j] == ' ' ? (byte)0x2F : (byte)(text[j] - 'A');
            b[12 + text.Length] = 0x7F; Bytes[Pool + (uint)index * 64] = b;
        }
        public bool TryRead(uint address, Span<byte> destination)
        {
            if (address == FailAddress) return false;
            reads.TryGetValue(address, out var count); reads[address] = count + 1;
            foreach (var (start, b) in Bytes)
            {
                if (address < start || address + (uint)destination.Length > start + b.Length) continue;
                b.AsSpan((int)(address - start), destination.Length).CopyTo(destination);
                if (address >= Pool && destination.Length > 12) TextReads.Add((int)((address - Pool) / 64));
                if (address == MutateOnSecondRead && count > 0) destination[0] ^= 1;
                return true;
            }
            return false;
        }
    }
}
