	// Launcher text in the 2013 Steam edition's four languages. The game
	// executable's language selects the table, as the stock launcher followed
	// the language of the installed depot.
	internal sealed class LauncherText
	{
		private static readonly string[] Codes = { "en", "fr", "de", "es" };
		private static readonly Dictionary<string, Dictionary<TextKey, string>> Tables = new Dictionary<string, Dictionary<TextKey, string>>(StringComparer.Ordinal)
		{
			{ "en", English() },
			{ "fr", French() },
			{ "de", German() },
			{ "es", Spanish() }
		};

		private readonly IReadOnlyDictionary<TextKey, string> table;
		private readonly CultureInfo culture;

		private LauncherText(string languageCode)
		{
			LanguageCode = languageCode;
			table = Tables[languageCode];
			culture = CultureInfo.GetCultureInfo(languageCode);
		}

		internal static IReadOnlyList<string> SupportedLanguageCodes => Codes;

		internal string LanguageCode { get; }

		internal string this[TextKey key] => table.TryGetValue(key, out string value) ? value : Tables["en"][key];

		internal static LauncherText For(string languageCode)
		{
			string code = (languageCode ?? string.Empty).Trim().ToLowerInvariant();
			return new LauncherText(Tables.ContainsKey(code) ? code : "en");
		}

		internal string Format(TextKey key, params object[] values)
		{
			return string.Format(culture, this[key], values);
		}

		internal bool Has(TextKey key)
		{
			return table.ContainsKey(key);
		}

		internal string LanguageName(string languageCode)
		{
			switch (languageCode)
			{
				case "fr":
					return this[TextKey.LanguageFrench];
				case "de":
					return this[TextKey.LanguageGerman];
				case "es":
					return this[TextKey.LanguageSpanish];
				default:
					return this[TextKey.LanguageEnglish];
			}
		}

