using System.Security.Cryptography;
using System.Text;
using Ff7.Accessibility.Reloaded;

namespace LocalizedDescriptionCueAligner;

/// <summary>One cue's place in one reviewed target identity.</summary>
internal sealed record IdentityCue(FieldCutsceneDescriptionCue Cue, int Entity, int Script, int ByteIndex);

/// <summary>A target field identity (exact prefix) and everything authorized or excluded in it.</summary>
internal sealed class ReviewedIdentity(int fieldId, string prefixSha256)
{
    public int FieldId { get; } = fieldId;
    public string PrefixSha256 { get; } = prefixSha256;
    public SortedSet<string> Languages { get; } = new(StringComparer.Ordinal);
    public List<IdentityCue> Cues { get; } = [];
    public List<(FieldCutsceneDescriptionCue Cue, string Reason)> Exclusions { get; } = [];
    public bool CreatureWarning { get; set; }
    public string Signature => string.Join(';', Cues.Select(c => $"{c.Cue.Key}>{c.Entity},{c.Script},{c.ByteIndex}")) + "#" +
                               string.Join(';', Exclusions.Select(e => $"{e.Cue.Key}:{e.Reason}")) + "#" + CreatureWarning;
}

internal static class ManifestWriter
{
    /// <summary>SHA-256 over every English anchor the runtime catalog contains, in a fixed order.</summary>
    public static string CatalogFingerprint(IEnumerable<FieldCutsceneDescriptionCue> cues) =>
        Convert.ToHexString(SHA256.HashData(Encoding.ASCII.GetBytes(string.Join('\n', cues
            .Select(c => $"{c.FieldId},{c.EntityId},{c.ScriptId},{c.ByteIndex},{c.Opcode}")
            .Order(StringComparer.Ordinal)))));

    public static string Write(IReadOnlyList<ReviewedIdentity> identities, IReadOnlyList<FieldCutsceneDescriptionCue> catalog,
        IReadOnlyList<string> sources)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("// Generated by tools/LocalizedDescriptionCueAligner from installed native field archives. Do not edit;");
        builder.AppendLine("// regenerate and review docs/localized-description-triggers-20261125.md instead.");
        foreach (var source in sources) builder.AppendLine("// " + source);
        builder.AppendLine($"// English catalog: {catalog.Count} anchors. Identities: {identities.Count}. " +
                           $"Authorized cue rows: {identities.Sum(i => i.Cues.Count)}. Exclusions: {identities.Sum(i => i.Exclusions.Count)}.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine("namespace Ff7.Accessibility.Reloaded;");
        builder.AppendLine();
        builder.AppendLine("public static partial class LocalizedFieldDescriptionCueManifest");
        builder.AppendLine("{");
        builder.AppendLine($"    internal const string GeneratedCatalogFingerprint = \"{CatalogFingerprint(catalog)}\";");
        builder.AppendLine($"    internal const int GeneratedCatalogAnchorCount = {catalog.Count};");
        builder.AppendLine();
        builder.AppendLine("    // @field,exact loaded prefix SHA-256,languages,reviewed creature warning MESSAGE (767 only)");
        builder.AppendLine("    // English entity,slot,byte,opcode                 the target runs it at the same coordinates");
        builder.AppendLine("    // English entity,slot,byte,opcode,entity,slot,byte  the target runs it at these coordinates");
        builder.AppendLine("    // !English entity,slot,byte,opcode,reason          the target identity never runs this cue");
        builder.AppendLine("    private const string RawIdentities = \"\"\"");
        foreach (var identity in identities.OrderBy(i => i.FieldId).ThenBy(i => i.PrefixSha256, StringComparer.Ordinal))
        {
            builder.AppendLine($"@{identity.FieldId},{identity.PrefixSha256},{string.Join('|', identity.Languages)},{(identity.CreatureWarning ? 1 : 0)}");
            foreach (var row in identity.Cues.OrderBy(c => c.Cue.EntityId).ThenBy(c => c.Cue.ScriptId).ThenBy(c => c.Cue.ByteIndex))
            {
                var key = $"{row.Cue.EntityId},{row.Cue.ScriptId},{row.Cue.ByteIndex},{row.Cue.Opcode}";
                builder.AppendLine(row.Entity == row.Cue.EntityId && row.Script == row.Cue.ScriptId && row.ByteIndex == row.Cue.ByteIndex
                    ? key
                    : $"{key},{row.Entity},{row.Script},{row.ByteIndex}");
            }

            foreach (var (cue, reason) in identity.Exclusions.OrderBy(e => e.Cue.EntityId).ThenBy(e => e.Cue.ScriptId).ThenBy(e => e.Cue.ByteIndex))
                builder.AppendLine($"!{cue.EntityId},{cue.ScriptId},{cue.ByteIndex},{cue.Opcode},{reason}");
        }

        builder.AppendLine("\"\"\";");
        builder.AppendLine("}");
        return builder.ToString();
    }
}
