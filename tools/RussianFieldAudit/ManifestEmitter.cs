using System.Text;
using System.Text.Json;

namespace RussianFieldAudit;

internal static class ManifestEmitter
{
    public static string Write(IReadOnlyList<ManifestRow> rows, string englishArchiveSha, string russianArchiveSha,
        int englishStockIdentities, int excluded, IReadOnlyList<int> routeUntrusted)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("// Generated by tools/RussianFieldAudit from the installed English flevel.lgp and the FFRTT Russian 1.02");
        builder.AppendLine("// flevel.lgp (ayumosa/ff7-7h-russian, RussianLanguage.FF7.7H.v1.02.iro). Do not edit; re-run the audit.");
        builder.AppendLine($"// english flevel.lgp sha256={englishArchiveSha}");
        builder.AppendLine($"// russian flevel.lgp sha256={russianArchiveSha}");
        builder.AppendLine($"// Rows: {rows.Count} ({rows.Count(r => r.Review == "semantic")} semantic, {rows.Count(r => r.Review == "reviewed")} reviewed). " +
                           $"Unchanged English prefixes: {englishStockIdentities}. Excluded: {excluded}.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine();
        builder.AppendLine("namespace Ff7.Accessibility.Reloaded;");
        builder.AppendLine();
        builder.AppendLine("public static partial class RussianFieldCompatibility");
        builder.AppendLine("{");
        builder.AppendLine($"    internal const string AuditedEnglishArchiveSha256 = \"{englishArchiveSha}\";");
        builder.AppendLine($"    internal const string AuditedRussianArchiveSha256 = \"{russianArchiveSha}\";");
        builder.AppendLine($"    internal const int GeneratedRowCount = {rows.Count};");
        builder.AppendLine($"    internal const int GeneratedUnchangedEnglishPrefixCount = {englishStockIdentities};");
        builder.AppendLine($"    internal const int GeneratedExcludedFieldCount = {excluded};");
        builder.AppendLine();
        builder.AppendLine("    // Fields whose installed English file does not describe the Russian field for routes planned from");
        builder.AppendLine("    // another field: entity shifts, route output differences, any edit beyond presentation, exclusions.");
        builder.AppendLine($"    private const string RawEnglishRouteUntrustedFields = \"{string.Join(',', routeUntrusted)}\";");
        builder.AppendLine();
        builder.AppendLine("    // Field, exact Russian prefix, the English disk prefix and model loader section it was audited");
        builder.AppendLine("    // against, how it was admitted, and (only where entity names differ) English -> Russian entities.");
        builder.AppendLine("    private const string RawRows = \"\"\"");
        foreach (var row in rows.OrderBy(r => r.Field))
        {
            var map = row.Map is null ? "" : ",\"Map\":" + JsonSerializer.Serialize(row.Map.ToDictionary(p => p.Key.ToString(), p => p.Value));
            builder.AppendLine($"{{\"Field\":{row.Field},\"Russian\":\"{row.Russian}\",\"English\":\"{row.English}\",\"EnglishModels\":\"{row.EnglishModels}\",\"Review\":\"{row.Review}\"{map}}}");
        }

        builder.AppendLine("\"\"\";");
        builder.AppendLine("}");
        return builder.ToString();
    }
}
